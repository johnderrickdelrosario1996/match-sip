-- 1. Bookings Table
CREATE TABLE IF NOT EXISTS public.bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_reference TEXT NOT NULL UNIQUE,
  selected_date TEXT NOT NULL,
  payment_method TEXT NOT NULL DEFAULT 'GCash (PayMongo)',
  customer_name TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  customer_email TEXT DEFAULT '',
  customer_notes TEXT DEFAULT '',
  slots JSONB NOT NULL DEFAULT '[]'::jsonb,
  total_amount NUMERIC NOT NULL DEFAULT 0,
  payment_proof_url TEXT DEFAULT '',
  status TEXT NOT NULL DEFAULT 'BOOKED',
  confirmed_at TEXT DEFAULT '',
  booked_at TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_bookings_selected_date ON public.bookings (selected_date);
CREATE INDEX IF NOT EXISTS idx_bookings_reference ON public.bookings (booking_reference);

-- 2. Court Slot Locks Table (Prevents double bookings via unique composite constraints & TTL holds)
CREATE TABLE IF NOT EXISTS public.court_slot_locks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lock_id TEXT NOT NULL UNIQUE,
  booking_reference TEXT NOT NULL,
  customer_name TEXT DEFAULT '',
  date TEXT NOT NULL,
  court_id TEXT NOT NULL,
  court_name TEXT DEFAULT '',
  time_label TEXT DEFAULT '',
  status TEXT NOT NULL DEFAULT 'BOOKED', -- 'BOOKED' (confirmed) or 'HELD' (temporary TTL hold)
  locked_at TEXT DEFAULT '',
  expires_at TIMESTAMPTZ, -- For 5-minute temporary checkout holds
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT unique_court_time_slot UNIQUE (date, court_id, time_label)
);

-- In case court_slot_locks already exists from an earlier migration, ensure columns & constraint exist:
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'court_slot_locks' AND column_name = 'expires_at') THEN
    ALTER TABLE public.court_slot_locks ADD COLUMN expires_at TIMESTAMPTZ;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints WHERE table_schema = 'public' AND table_name = 'court_slot_locks' AND constraint_name = 'unique_court_time_slot') THEN
    BEGIN
      ALTER TABLE public.court_slot_locks ADD CONSTRAINT unique_court_time_slot UNIQUE (date, court_id, time_label);
    EXCEPTION WHEN duplicate_table OR duplicate_object THEN
      -- Constraint already exists
    END;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_slot_locks_lock_id ON public.court_slot_locks (lock_id);
CREATE INDEX IF NOT EXISTS idx_slot_locks_date ON public.court_slot_locks (date);
CREATE INDEX IF NOT EXISTS idx_slot_locks_composite ON public.court_slot_locks (date, court_id, time_label);
CREATE INDEX IF NOT EXISTS idx_slot_locks_expires ON public.court_slot_locks (expires_at) WHERE status = 'HELD';

-- Atomic Transaction with Row-Level Locking (SELECT ... FOR UPDATE)
CREATE OR REPLACE FUNCTION public.claim_court_slots(
  p_booking_reference TEXT,
  p_customer_name TEXT,
  p_selected_date TEXT,
  p_slots JSONB,
  p_is_temp_hold BOOLEAN DEFAULT FALSE,
  p_hold_ttl_seconds INT DEFAULT 300
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_slot JSONB;
  v_court_id TEXT;
  v_court_name TEXT;
  v_time_label TEXT;
  v_time_key TEXT;
  v_lock_id TEXT;
  v_existing_lock RECORD;
  v_now TIMESTAMPTZ := NOW();
  v_expires_at TIMESTAMPTZ;
  v_status TEXT;
BEGIN
  IF p_is_temp_hold THEN
    v_status := 'HELD';
    v_expires_at := v_now + (p_hold_ttl_seconds || ' seconds')::INTERVAL;
  ELSE
    v_status := 'BOOKED';
    v_expires_at := NULL;
  END IF;

  -- Iterate through every requested slot inside an atomic transaction
  FOR v_slot IN SELECT * FROM jsonb_array_elements(p_slots)
  LOOP
    v_court_id := lower(trim(COALESCE(v_slot->>'courtId', 'court-1')));
    v_court_name := COALESCE(v_slot->>'courtName', 'Court');
    v_time_label := COALESCE(v_slot->>'timeLabel', '');
    v_time_key := COALESCE(substring(v_time_label from '([0-9]{1,2}:[0-9]{2})'), '08:00');
    v_time_key := replace(v_time_key, ':', '');
    v_lock_id := p_selected_date || '_' || v_court_id || '_' || v_time_key;

    -- 1. Row-level lock via SELECT ... FOR UPDATE
    SELECT * INTO v_existing_lock
    FROM public.court_slot_locks
    WHERE lock_id = v_lock_id
    FOR UPDATE;

    IF FOUND THEN
      -- Check if slot is actively booked OR held by another user with unexpired TTL
      IF v_existing_lock.status = 'BOOKED' AND v_existing_lock.booking_reference <> p_booking_reference THEN
        RAISE EXCEPTION 'DOUBLE_BOOKING_PREVENTED: Slot "% (%)" is already confirmed by another player.', v_court_name, v_time_label;
      ELSIF v_existing_lock.status = 'HELD' 
            AND v_existing_lock.expires_at > v_now 
            AND v_existing_lock.booking_reference <> p_booking_reference THEN
        RAISE EXCEPTION 'SLOT_HELD_IN_PROGRESS: Slot "% (%)" is currently in checkout by another player. Please try again shortly.', v_court_name, v_time_label;
      END IF;

      -- Slot lock exists but is either:
      -- a) Same bookingReference renewing/confirming its hold, OR
      -- b) An expired hold that can be safely reclaimed
      UPDATE public.court_slot_locks
      SET booking_reference = p_booking_reference,
          customer_name = p_customer_name,
          date = p_selected_date,
          court_id = v_court_id,
          court_name = v_court_name,
          time_label = v_time_label,
          status = v_status,
          locked_at = to_char(v_now, 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
          expires_at = v_expires_at
      WHERE lock_id = v_lock_id;
    ELSE
      -- Insert brand new lock protected by UNIQUE (date, court_id, time_label) constraint
      INSERT INTO public.court_slot_locks (
        lock_id,
        booking_reference,
        customer_name,
        date,
        court_id,
        court_name,
        time_label,
        status,
        locked_at,
        expires_at
      ) VALUES (
        v_lock_id,
        p_booking_reference,
        p_customer_name,
        p_selected_date,
        v_court_id,
        v_court_name,
        v_time_label,
        v_status,
        to_char(v_now, 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
        v_expires_at
      );
    END IF;
  END LOOP;

  RETURN jsonb_build_object(
    'success', true,
    'bookingReference', p_booking_reference,
    'status', v_status,
    'expiresAt', v_expires_at
  );
END;
$$;

-- 3. Visitor Analytics Table (Rolling 48-Hour Security & Activity Audit)
CREATE TABLE IF NOT EXISTS public.visitor_analytics (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_address VARCHAR(255) NOT NULL,
  action TEXT NOT NULL,
  user_agent TEXT DEFAULT '',
  timestamp TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_visitor_analytics_timestamp ON public.visitor_analytics (timestamp DESC);

-- 4. Users Table (Synced with Firebase Auth UID)
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_users_uid ON public.users (uid);

-- 5. App Settings Table (Dynamic Maintenance Mode & System Settings)
CREATE TABLE IF NOT EXISTS public.app_settings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key TEXT NOT NULL UNIQUE,
  value JSONB NOT NULL DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_app_settings_key ON public.app_settings (key);

-- 6. Row Level Security (RLS) Configuration
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.court_slot_locks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.visitor_analytics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_settings ENABLE ROW LEVEL SECURITY;

-- Allow public access via Supabase anon key
DROP POLICY IF EXISTS "Public access for bookings" ON public.bookings;
CREATE POLICY "Public access for bookings" ON public.bookings FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access for court_slot_locks" ON public.court_slot_locks;
CREATE POLICY "Public access for court_slot_locks" ON public.court_slot_locks FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access for visitor_analytics" ON public.visitor_analytics;
CREATE POLICY "Public access for visitor_analytics" ON public.visitor_analytics FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access for users" ON public.users;
CREATE POLICY "Public access for users" ON public.users FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access for app_settings" ON public.app_settings;
CREATE POLICY "Public access for app_settings" ON public.app_settings FOR ALL USING (true) WITH CHECK (true);

